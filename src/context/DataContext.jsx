function loadState() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return demoData;
    const parsed = JSON.parse(raw);
    return { ...demoData, ...parsed };
  } catch {
    return demoData;
  }
}

function saveState(state) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch {}
}

export function DataProvider({ children }) {
  const [state, setState] = useState(loadState);

  useEffect(() => {
    saveState(state);
  }, [state]);

  const api = useMemo(
    () => ({
      state,
      setSlides: (slides) => setState((s) => ({ ...s, slides })),
      setNews: (news) => setState((s) => ({ ...s, news })),
      setEvents: (events) => setState((s) => ({ ...s, events })),
      setDeputies: (deputies) => setState((s) => ({ ...s, deputies })),
      setDocuments: (documents) => setState((s) => ({ ...s, documents })),
      setAppeals: (appeals) => setState((s) => ({ ...s, appeals })),
      setSettings: (settings) =>
        setState((s) => ({ ...s, settings: { ...s.settings, ...settings } })),
      register: ({ email, password }) =>
        setState((s) => {
          const exists = s.users.find((u) => u.email === email);
          if (exists) return s;
          const user = {
            id: "u" + Date.now(),
            email,
            passwordHash: password,
            role: "citizen",
          };
          return {
            ...s,
            users: [...s.users, user],
            sessions: { currentUserId: user.id },
          };
        }),
      login: ({ email, password }) =>
        setState((s) => {
          const user = s.users.find(
            (u) => u.email === email && u.passwordHash === password
          );
          if (!user) return s;
          return { ...s, sessions: { currentUserId: user.id } };
        }),
      logout: () =>
        setState((s) => ({ ...s, sessions: { currentUserId: null } })),
      addAppeal: (appeal) =>
        setState((s) => ({
          ...s,
          appeals: [
            ...s.appeals,
            { ...appeal, id: "a" + Date.now(), status: "Принято" },
          ],
        })),
      updateAppealStatus: (id, status) =>
        setState((s) => ({
          ...s,
          appeals: s.appeals.map((a) => (a.id === id ? { ...a, status } : a)),
        })),
      addDocument: (doc) =>
        setState((s) => ({
          ...s,
          documents: [...s.documents, { ...doc, id: "doc" + Date.now() }],
        })),
      updateDocument: (id, patch) =>
        setState((s) => ({
          ...s,
          documents: s.documents.map((d) =>
            d.id === id ? { ...d, ...patch } : d
          ),
        })),
      deleteDocument: (id) =>
        setState((s) => ({
          ...s,
          documents: s.documents.filter((d) => d.id !== id),
        })),
      addNews: (item) =>
        setState((s) => ({
          ...s,
          news: [{ ...item, id: "n" + Date.now() }, ...s.news],
        })),
      deleteNews: (id) =>
        setState((s) => ({ ...s, news: s.news.filter((n) => n.id !== id) })),
      addEvent: (ev) =>
        setState((s) => ({
          ...s,
          events: [...s.events, { ...ev, id: "e" + Date.now() }],
        })),
      deleteEvent: (id) =>
        setState((s) => ({
          ...s,
          events: s.events.filter((e) => e.id !== id),
        })),
      setSlidesOrder: (slides) => setState((s) => ({ ...s, slides })),
      addSlide: (slide) =>
        setState((s) => ({
          ...s,
          slides: [{ ...slide, id: "s" + Date.now() }, ...s.slides].slice(0, 5),
        })),
      deleteSlide: (id) =>
        setState((s) => ({
          ...s,
          slides: s.slides.filter((sl) => sl.id !== id),
        })),
      addDeputy: (dep) =>
        setState((s) => ({
          ...s,
          deputies: [...s.deputies, { ...dep, id: "d" + Date.now() }],
        })),
      updateDeputy: (id, patch) =>
        setState((s) => ({
          ...s,
          deputies: s.deputies.map((d) =>
            d.id === id ? { ...d, ...patch } : d
          ),
        })),
      deleteDeputy: (id) =>
        setState((s) => ({
          ...s,
          deputies: s.deputies.filter((d) => d.id !== id),
        })),
      addComment: (newsId, comment) =>
        setState((s) => {
          const list = s.comments[newsId] || [];
          return {
            ...s,
            comments: {
              ...s.comments,
              [newsId]: [...list, { id: "c" + Date.now(), ...comment }],
            },
          };
        }),
      deleteComment: (newsId, commentId) =>
        setState((s) => {
          const list = s.comments[newsId] || [];
          return {
            ...s,
            comments: {
              ...s.comments,
              [newsId]: list.filter((c) => c.id !== commentId),
            },
          };
        }),
    }),
    [state]
  );

  return <DataContext.Provider value={api}>{children}</DataContext.Provider>;
}

export function useData() {
  const ctx = useContext(DataContext);
  if (!ctx) throw new Error("useData must be used within DataProvider");
  return ctx;
}
